import { assertOpenAIAPIKeyConnector } from '../../../infrastructure/providers/openai/OpenAIAuth.js';
import { Connector } from '../../../core/Connector.js';
import type {
  OpenAIRealtimeClientSecret,
  OpenAIRealtimeSessionConfig,
  OpenAIRealtimeTranscriptionSessionConfig,
  OpenAIRealtimeTranslationClientSessionConfig,
} from './RealtimeTypes.js';
import { assertOpenAIRealtimePCMRates } from './RealtimeTypes.js';
import type { OpenAIRealtimeWebRTCCall } from './RealtimeChannel.js';

export interface CreateRealtimeClientSecretOptions {
  session: OpenAIRealtimeSessionConfig | OpenAIRealtimeTranscriptionSessionConfig;
  expiresAfterSeconds?: number;
  safetyIdentifier?: string;
}

export interface CreateRealtimeTranslationClientSecretOptions {
  session: OpenAIRealtimeTranslationClientSessionConfig;
  safetyIdentifier?: string;
}

export interface CreateRealtimeWebRTCCallOptions {
  /** SDP offer generated by RTCPeerConnection.createOffer(). */
  sdp: string;
  /** Optional initial session configuration sent atomically with the offer. */
  session?: OpenAIRealtimeSessionConfig;
  safetyIdentifier?: string;
}

/** REST helpers for browser/WebRTC credentials and server-side SIP call control. */
export class OpenAIRealtimeAPI {
  readonly connector: Connector;

  constructor(connector: string | Connector) {
    this.connector = typeof connector === 'string' ? Connector.get(connector) : connector;
    assertOpenAIAPIKeyConnector(this.connector, 'OpenAIRealtimeAPI');
  }

  async createClientSecret(options: CreateRealtimeClientSecretOptions): Promise<OpenAIRealtimeClientSecret> {
    assertOpenAIRealtimePCMRates(options.session);
    if (options.expiresAfterSeconds !== undefined
      && (options.expiresAfterSeconds < 10 || options.expiresAfterSeconds > 7200)) {
      throw new RangeError('expiresAfterSeconds must be between 10 and 7200');
    }
    return this.request('/realtime/client_secrets', {
      session: options.session,
      ...(options.expiresAfterSeconds === undefined ? {} : {
        expires_after: { anchor: 'created_at', seconds: options.expiresAfterSeconds },
      }),
    }, options.safetyIdentifier) as Promise<OpenAIRealtimeClientSecret>;
  }

  async createTranslationClientSecret(
    options: CreateRealtimeTranslationClientSecretOptions,
  ): Promise<OpenAIRealtimeClientSecret> {
    return this.request('/realtime/translations/client_secrets', {
      session: options.session,
    }, options.safetyIdentifier) as Promise<OpenAIRealtimeClientSecret>;
  }

  /** Exchange a WebRTC SDP offer for the SDP answer (backward-compatible API). */
  async createWebRTCCall(options: CreateRealtimeWebRTCCallOptions): Promise<string> {
    return (await this.exchangeWebRTCCall(options)).sdp;
  }

  /** Exchange a WebRTC SDP offer for the SDP answer and sideband call ID. */
  async createWebRTCCallWithMetadata(
    options: CreateRealtimeWebRTCCallOptions,
  ): Promise<OpenAIRealtimeWebRTCCall> {
    const { sdp, response } = await this.exchangeWebRTCCall(options);
    const callId = parseCallId(response.headers.get('Location'));
    if (!callId) {
      throw new Error('OpenAI Realtime WebRTC response did not include a call ID in the Location header');
    }
    return { sdp, callId };
  }

  private async exchangeWebRTCCall(
    options: CreateRealtimeWebRTCCallOptions,
  ): Promise<{ sdp: string; response: Response }> {
    if (!options.sdp.trim()) throw new RangeError('sdp must not be empty');
    if (options.session) assertOpenAIRealtimePCMRates(options.session);
    const form = new FormData();
    form.set('sdp', options.sdp);
    if (options.session) {
      form.set('session', JSON.stringify({ ...options.session, type: 'realtime' }));
    }
    const response = await this.requestResponse(
      '/realtime/calls',
      form,
      options.safetyIdentifier,
      'multipart',
    );
    const sdp = await response.text();
    if (!sdp.trim()) throw new Error('OpenAI Realtime WebRTC response did not include an SDP answer');
    return { sdp, response };
  }

  async acceptCall(callId: string, session: OpenAIRealtimeSessionConfig): Promise<void> {
    assertOpenAIRealtimePCMRates(session);
    await this.request(`/realtime/calls/${encodeURIComponent(callId)}/accept`, {
      ...session,
      type: 'realtime',
    });
  }

  async rejectCall(callId: string, statusCode?: number): Promise<void> {
    await this.request(`/realtime/calls/${encodeURIComponent(callId)}/reject`,
      statusCode === undefined ? {} : { status_code: statusCode });
  }

  async hangupCall(callId: string): Promise<void> {
    // Closing the WebRTC peer and asking the trusted host to release the call
    // are intentionally concurrent. If peer closure wins that race, OpenAI
    // reports call_id_not_found; the requested terminal state is already true.
    await this.request(
      `/realtime/calls/${encodeURIComponent(callId)}/hangup`,
      undefined,
      undefined,
      'json',
      [404],
    );
  }

  async referCall(callId: string, targetUri: string): Promise<void> {
    await this.request(`/realtime/calls/${encodeURIComponent(callId)}/refer`, { target_uri: targetUri });
  }

  private async request(
    path: string,
    body?: Record<string, unknown>,
    safetyIdentifier?: string,
    responseType: 'json' | 'text' = 'json',
    acceptedStatuses: readonly number[] = [],
  ): Promise<unknown> {
    const response = await this.requestResponse(
      path,
      body,
      safetyIdentifier,
      'json',
      acceptedStatuses,
    );
    if (!response.ok) return undefined;
    if (response.status === 204) return undefined;
    const text = await response.text();
    if (responseType === 'text') return text;
    return text ? JSON.parse(text) : undefined;
  }

  private async requestResponse(
    path: string,
    body?: Record<string, unknown> | FormData,
    safetyIdentifier?: string,
    encoding: 'json' | 'multipart' = 'json',
    acceptedStatuses: readonly number[] = [],
  ): Promise<Response> {
    const base = this.connector.baseURL || 'https://api.openai.com/v1';
    const url = `${base.replace(/\/$/, '')}/${path.replace(/^\//, '')}`;
    const response = await this.connector.fetch(url, {
      method: 'POST',
      headers: {
        ...(encoding === 'json' ? { 'Content-Type': 'application/json' } : {}),
        ...(safetyIdentifier ? { 'OpenAI-Safety-Identifier': safetyIdentifier } : {}),
      },
      ...(body === undefined ? {} : {
        body: encoding === 'json' ? JSON.stringify(body) : body as FormData,
      }),
    });
    if (!response.ok && !acceptedStatuses.includes(response.status)) {
      const detail = await response.text();
      throw new Error(`OpenAI Realtime API ${response.status}: ${detail || response.statusText}`);
    }
    return response;
  }
}

function parseCallId(location: string | null): string | null {
  if (!location) return null;
  const match = location.match(/\/realtime\/calls\/([^/?#]+)/i);
  if (!match?.[1]) return null;
  try {
    return decodeURIComponent(match[1]);
  } catch {
    return match[1];
  }
}
